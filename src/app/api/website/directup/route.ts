// DirectUP: what the gateway on Railway says about itself - status, usage, the tool's log, order lists, the
// installation snippets - read for the hub's page (Website's grant). Changes - the batch size, a catalogue
// pull, new snippets, the gateway's address - are admins' only. Same three answers as every integration
// route: not configured, upstream failed (with the reason), or the data.
//   GET  ?part=overview&days=30 | log | jobs | job&id= | snippets
//   POST { action: "settings", batchSize } | { action: "sync" } | { action: "regenerate" } | { action: "gateway", url }

import { NextRequest, NextResponse } from "next/server";
import { myAccess } from "@/lib/auth/appAccess";
import { requireUser } from "@/lib/auth/guard";
import { adminKey, gateway, gatewaySetting, setGateway, type JobDetail, type JobSummary, type Log, type Snippets, type Status, type Usage } from "@/lib/directup/gateway";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";
export const maxDuration = 60;

const fail = (err: unknown) => NextResponse.json({
  configured: true, ok: false, error: String((err as Error)?.message ?? err), status: (err as { status?: number })?.status ?? null,
});

export async function GET(req: NextRequest) {
  const access = await myAccess();
  if (!access) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  if (!access.canOpen("website")) return NextResponse.json({ error: "No access" }, { status: 403 });
  if (!adminKey()) return NextResponse.json({ configured: false, missing: ["DIRECTUP_ADMIN_KEY"] });
  const q = req.nextUrl.searchParams;
  const part = q.get("part") || "overview";
  try {
    const setting = await gatewaySetting();
    const isAdmin = access.role === "admin";
    if (part === "overview") {
      const days = Math.min(365, Math.max(1, parseInt(q.get("days") || "30", 10) || 30));
      const [status, usage] = await Promise.all([gateway<Status>("/status"), gateway<Usage>(`/usage?days=${days}`)]);
      return NextResponse.json({ configured: true, ok: true, data: { setting, status, usage, isAdmin } });
    }
    if (part === "log") {
      // the last 1,000 events (the gateway's most): the page sorts them into topics and pages through them
      const log = await gateway<Log>("/log?n=1000");
      return NextResponse.json({ configured: true, ok: true, data: log });
    }
    if (part === "jobs") return NextResponse.json({ configured: true, ok: true, data: await gateway<{ jobs: JobSummary[] }>("/jobs?n=100") });
    if (part === "job") {
      const id = q.get("id") || "";
      if (!/^[0-9a-f-]{8,64}$/i.test(id)) return NextResponse.json({ configured: true, ok: false, error: "No such order list.", status: 400 });
      return NextResponse.json({ configured: true, ok: true, data: await gateway<JobDetail>(`/jobs/${id}`) });
    }
    if (part === "snippets") {
      const snippets = await gateway<Snippets>("/snippets");
      return NextResponse.json({ configured: true, ok: true, data: { setting, snippets, isAdmin } });
    }
    return NextResponse.json({ configured: true, ok: false, error: "Unknown part.", status: 400 });
  } catch (err) {
    return fail(err);
  }
}

export async function POST(req: NextRequest) {
  const access = await myAccess();
  if (!access) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  if (access.role !== "admin") return NextResponse.json({ ok: false, error: "Admins only." }, { status: 403 });
  const body = (await req.json().catch(() => ({}))) as { action?: string; batchSize?: unknown; url?: unknown };
  const me = await requireUser();
  const who = me.full_name || me.username;
  try {
    if (body.action === "settings") {
      const n = Number(body.batchSize);
      if (!Number.isInteger(n) || n < 1 || n > 100) return NextResponse.json({ ok: false, error: "Lines per request: 1 to 100." }, { status: 400 });
      const data = await gateway<{ batchSize: number }>("/settings", { method: "PUT", body: { batchSize: n } });
      console.log(`[directup] lines per request set to ${n} by ${who}`);
      return NextResponse.json({ ok: true, data });
    }
    if (body.action === "sync") return NextResponse.json({ ok: true, data: await gateway<{ started: boolean }>("/catalogue/sync", { method: "POST" }) });
    if (body.action === "regenerate") {
      const data = await gateway<Snippets>("/snippets/regenerate", { method: "POST" });
      console.log(`[directup] installation snippets regenerated by ${who}`);
      return NextResponse.json({ ok: true, data });
    }
    if (body.action === "gateway") {
      if (typeof body.url !== "string") return NextResponse.json({ ok: false, error: "No address given." }, { status: 400 });
      const setting = await setGateway(body.url, who);
      console.log(`[directup] gateway address set to ${setting.url} by ${who}`);
      return NextResponse.json({ ok: true, data: { setting } });
    }
    return NextResponse.json({ ok: false, error: "Unknown action." }, { status: 400 });
  } catch (err) {
    return NextResponse.json({ ok: false, error: String((err as Error)?.message ?? err) }, { status: 502 });
  }
}
