// THE USE CASES OVERVIEW'S CARDS - three KPIs per UC, side by side (SARCLA
// 13.10.2026: "3 main KPIs in one block for each UC"). A ticket flow shows its
// win rate, its top 5 resolutions and the revenue it generated; a flow without
// tickets shows its own rate, its top outcomes and its money where it has one.
// Worked out from each UC's cached read, for the hub-wide period - nothing here
// reads HubSpot.

import { HUB_UCS, QUAL_KINDS, UCS, type UcKey } from "./config";
import { inWin, monthOf, revenueBetween, tally, type Win } from "./rules";
import { VIEWS, WIN_UCS, resolutionOf, uc2Cohort, whoQualified } from "./views";
import type { CardSlot, UcCard, UcData, View } from "./types";
import { isClosed, isWon, outcomeLabel, type ErosionTicket } from "../erosion/model";

const valueOf = (v: View, label: string): number | null => {
  const x = v.tiles.find((t) => t.label === label)?.value;
  return typeof x === "number" ? x : null;
};
const n0 = (n: number) => n.toLocaleString("en-US");

/** Erosion's rule on any ticket flow: won = closed with the answer Ordered; the top 5 answers of the closed tickets. */
export function ticketSlots(tickets: ErosionTicket[]): Pick<UcCard, "a" | "top"> {
  const closed = tickets.filter(isClosed);
  const won = closed.filter(isWon).length;
  return {
    a: { label: "Win rate", value: closed.length ? won / closed.length : null, fmt: "pct", note: `${n0(won)} of ${n0(closed.length)} closed tickets ended in an order` },
    top: {
      label: "Top 5 resolutions",
      rows: tally(closed.map(outcomeLabel)).slice(0, 5).map((r) => ({ label: r.label, n: r.n, won: r.label === "Ordered" })),
      total: closed.length,
    },
  };
}

/**
 * Revenue generated by a ticket flow: the ERP revenue, from the month of its
 * first ticket in the period, of every company that ordered (real orders) on or
 * after that ticket.
 */
export function ticketRevenue(d: UcData, win: Win): CardSlot {
  const first = new Map<string, string>();
  for (const t of d.tickets) {
    if (!t.companyId || !inWin(t.created, win)) continue;
    const f = first.get(t.companyId);
    if (!f || t.created < f) first.set(t.companyId, t.created);
  }
  const to = monthOf(d.today);
  let sum = 0, n = 0;
  for (const [id, day] of first) {
    const c = d.ticketCos?.[id];
    if (!c?.last || c.last < day) continue;
    n += 1;
    sum += revenueBetween(c.rev, monthOf(day), to);
  }
  return {
    label: "Revenue generated", value: d.ticketCos ? sum : null, fmt: "eur",
    note: d.ticketCos ? `ERP revenue since the ticket · ${n0(n)} ${n === 1 ? "company" : "companies"} that ordered after it` : "read with the next refresh",
  };
}

/** One lifecycle UC's card from its cached read; null data = still being read for the first time. */
export function cardOf(key: UcKey, d: UcData | null, win: Win): UcCard {
  const uc = UCS.find((u) => u.key === key)!;
  const base = { code: uc.code, title: uc.title, href: uc.href };
  if (!d) return { ...base, a: null, top: null, b: null, reading: true };

  if (WIN_UCS.includes(key)) {
    return { ...base, ...ticketSlots(resolutionOf(key, d, win)?.tickets ?? []), b: ticketRevenue(d, win) };
  }

  if (key === "uc2") {
    const inW = uc2Cohort(d).filter((x) => !x.already && inWin(x.mql, win));
    const t = whoQualified(inW.map((x) => x.c), d.people ?? {});
    const sum = (k: string) => (t.kind === "table" ? t.rows.reduce((a, r) => a + (Number(r[k]) || 0), 0) : 0);
    const yes = sum("yes"), no = sum("no"), open = sum("open");
    const to = monthOf(d.today);
    const buyers = inW.filter((x) => x.order === "yes" && x.c.first);
    const revenue = buyers.reduce((a, x) => a + revenueBetween(x.c.rev, monthOf(x.c.first!), to), 0);
    const rows = [...QUAL_KINDS.map((k) => ({ label: k.label, n: sum(k.key) })), { label: "Disqualified", n: no }, { label: "Not decided yet", n: open }]
      .filter((r) => r.n > 0).sort((a, b) => b.n - a.n).slice(0, 5);
    return {
      ...base,
      a: { label: "Qualified", value: yes + no ? yes / (yes + no) : null, fmt: "pct", note: `${n0(yes)} of ${n0(yes + no)} decided · ${n0(open)} not decided yet` },
      top: { label: "Qualification answers", rows, total: yes + no + open },
      b: { label: "Revenue generated", value: revenue, fmt: "eur", note: `ERP revenue of the ${n0(buyers.length)} new MQLs that bought within 90 days` },
    };
  }

  const v = VIEWS[key](d, null, win);

  if (key === "uc10") {
    const reasons = v.charts.find((c) => c.kind === "bars" && c.title === "Why they did not buy again");
    const rows = reasons && reasons.kind === "bars" ? reasons.rows.slice(0, 5).map((r) => ({ label: r.label, n: r.value })) : [];
    return {
      ...base,
      a: { label: "Promoted to Loyalty / Retain", value: valueOf(v, "Promoted to Loyalty / Retain"), fmt: "n", note: "reached 12 orders in the period" },
      top: { label: "Why they did not buy again", rows, total: reasons && reasons.kind === "bars" ? reasons.rows.reduce((a, r) => a + r.value, 0) : 0 },
      b: { label: "Past their usual reorder", value: valueOf(v, "Past their usual reorder"), fmt: "n", note: "Grow / Nurture companies due a call" },
    };
  }

  if (key === "uc13") {
    const re = valueOf(v, "Reactivated") ?? 0, not = valueOf(v, "Not reactivated") ?? 0, open = valueOf(v, "Still open") ?? 0;
    return {
      ...base,
      a: { label: "Reactivation rate", value: re + not ? re / (re + not) : null, fmt: "pct", note: `${n0(re)} of ${n0(re + not)} decided · ${n0(open)} still open` },
      top: { label: "What followed", rows: [{ label: "Reactivated", n: re, won: true }, { label: "Not reactivated", n: not }, { label: "Still open", n: open }].filter((r) => r.n > 0), total: re + not + open },
      b: { label: "Revenue generated", value: valueOf(v, "Revenue since reactivation"), fmt: "eur", note: "ERP revenue since reactivation" },
    };
  }

  // uc12
  const flagged = valueOf(v, "Companies flagged") ?? 0, held = valueOf(v, "Revenue held") ?? 0;
  return {
    ...base,
    a: { label: "Revenue held", value: flagged ? held / flagged : null, fmt: "pct", note: `${n0(held)} of ${n0(flagged)} flagged companies` },
    top: {
      label: "The flags",
      rows: [
        { label: "Tasks done", n: valueOf(v, "Tasks done") ?? 0 },
        { label: "Revenue held", n: held, won: true },
        { label: "Also an erosion ticket", n: valueOf(v, "Also an erosion ticket") ?? 0 },
      ].filter((r) => r.n > 0),
      total: flagged,
    },
    b: { label: "Revenue 3 months after", value: valueOf(v, "3 months after the flag"), fmt: "eur", note: "flagged companies, the 3 months after the flag" },
  };
}

/** UC16 / UC17: the hub's own ticket flows, from their own ticket reads. */
export function hubCard(code: "UC16" | "UC17", tickets: ErosionTicket[] | null, win: Win, opts: { valuesShown: boolean; error?: string | null }): UcCard {
  const h = HUB_UCS.find((u) => u.code === code)!;
  const base = { code: h.code, title: h.title, href: h.href };
  if (!tickets) return { ...base, a: null, top: null, b: null, reading: !opts.error, error: opts.error ?? null };
  const tW = tickets.filter((t) => t.created >= win.from && t.created <= win.to);
  const wonEur = tW.filter(isWon).reduce((a, t) => a + (t.amount || 0), 0);
  const b: CardSlot = code === "UC16"
    ? { label: "Won back", value: wonEur, fmt: "eur", note: "last year's revenue on the won tickets' articles" }
    : opts.valuesShown
      ? { label: "Won back", value: wonEur, fmt: "eur", note: "priced and not ordered, on the won tickets" }
      : { label: "Revenue generated", value: null, fmt: "eur", note: "not shown: prices are per ERP unit" };
  return { ...base, ...ticketSlots(tW), b };
}
